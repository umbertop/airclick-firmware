// Bridge ESP32 (USART1) -> USB-CDC: accumulate a line and forward it once a
// newline arrives, so wireless-button data appears on the same stream as the
// wired PBx buttons.
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1)
  {
    if (uart_rx_byte == '\n' || uart_line_len >= sizeof(uart_line) - 2)
    {
      uart_line[uart_line_len] = '\r';
      uart_line[uart_line_len + 1] = '\n';
      CDC_Transmit_FS((uint8_t *)uart_line, uart_line_len + 2);
      uart_line_len = 0;
    }
    else if (uart_rx_byte != '\r')
    {
      uart_line[uart_line_len++] = (char)uart_rx_byte;
    }
    HAL_UART_Receive_IT(&huart1, &uart_rx_byte, 1);
  }
}
